use anyhow::{bail, Context, Result};
use std::{
    ffi::OsStr,
    fs,
    path::{Path, PathBuf},
};

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DictionaryEntry {
    pub name: Option<String>,
    pub value: Vec<u8>,
}

#[derive(Copy, Clone, Debug, Eq, PartialEq)]
pub enum DictionaryFormat {
    Auto,
    LibFuzzer,
    WordList,
}

/// Parse one libFuzzer/AFL dictionary file.
///
/// The grammar intentionally follows the small subset documented by LLVM:
/// blank lines and `#` comments are ignored, entries may be named
/// (`name="value"`) and values use Rust/C-style escapes plus `\xHH`.
pub fn parse_dictionary(input: &str) -> Result<Vec<DictionaryEntry>> {
    let mut entries = Vec::new();

    for (line_number, original_line) in input.lines().enumerate() {
        let line = original_line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        let (name, raw_value) = if line.starts_with('"') {
            (None, line)
        } else if let Some((name, value)) = line.split_once('=') {
            (Some(name.trim().to_owned()), value.trim())
        } else {
            (None, line)
        };

        let value = if raw_value.starts_with('"') {
            parse_quoted_value(raw_value)
                .with_context(|| format!("invalid dictionary entry on line {}", line_number + 1))?
        } else {
            raw_value.as_bytes().to_vec()
        };

        if value.is_empty() {
            bail!("dictionary entry on line {} is empty", line_number + 1);
        }

        entries.push(DictionaryEntry { name, value });
    }

    Ok(deduplicate(entries))
}

/// Parse a newline-separated word list. Unlike [`parse_dictionary`], every
/// non-comment line is treated as one literal token.
pub fn parse_word_list(input: &str) -> Vec<DictionaryEntry> {
    let entries = input
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(|line| DictionaryEntry {
            name: None,
            value: line.as_bytes().to_vec(),
        })
        .collect();
    deduplicate(entries)
}

pub fn parse_source(path: &Path, format: DictionaryFormat) -> Result<Vec<DictionaryEntry>> {
    let metadata = fs::metadata(path)
        .with_context(|| format!("cannot read dictionary source {}", path.display()))?;

    if metadata.is_dir() {
        return import_directory(path, format);
    }

    let input = fs::read_to_string(path)
        .with_context(|| format!("dictionary source is not valid UTF-8: {}", path.display()))?;
    let looks_like_word_list = matches!(
        path.extension().and_then(OsStr::to_str),
        Some("txt" | "words")
    );

    match format {
        DictionaryFormat::WordList => Ok(parse_word_list(&input)),
        DictionaryFormat::LibFuzzer => parse_dictionary(&input),
        DictionaryFormat::Auto if looks_like_word_list => Ok(parse_word_list(&input)),
        DictionaryFormat::Auto => parse_dictionary(&input),
    }
}

pub fn serialize_dictionary(entries: &[DictionaryEntry]) -> String {
    let mut output = String::from("# Generated by `cargo fuzz dictionary import`\n");
    for (index, entry) in entries.iter().enumerate() {
        let name = entry
            .name
            .clone()
            .filter(|name| is_valid_identifier(name))
            .unwrap_or_else(|| format!("token_{:04}", index + 1));
        output.push_str(&name);
        output.push('=');
        output.push('"');
        output.push_str(&escape_value(&entry.value));
        output.push('"');
        output.push('\n');
    }
    output
}

pub fn merge_entries(
    existing: Vec<DictionaryEntry>,
    incoming: Vec<DictionaryEntry>,
) -> Vec<DictionaryEntry> {
    let mut merged = existing;
    merged.extend(incoming);
    deduplicate(merged)
}

pub fn dictionary_dir(fuzz_dir: &Path) -> PathBuf {
    fuzz_dir.join("dictionaries")
}

pub fn default_dictionary_path(fuzz_dir: &Path, target: &str) -> PathBuf {
    dictionary_dir(fuzz_dir).join(format!("{target}.dict"))
}

/// Resolve a user-supplied dictionary reference.
///
/// A path that exists is used as-is. Otherwise bare names are resolved in the
/// project's `fuzz/dictionaries` directory, with or without `.dict`.
pub fn resolve_dictionary(reference: &Path, fuzz_dir: &Path) -> Result<PathBuf> {
    if reference.exists() {
        return Ok(reference.to_path_buf());
    }

    let file_name = reference.file_name().map(Path::new).unwrap_or(reference);
    let candidate = dictionary_dir(fuzz_dir).join(file_name);
    if candidate.exists() {
        return Ok(candidate);
    }

    let mut with_extension = file_name.as_os_str().to_owned();
    with_extension.push(".dict");
    let candidate = dictionary_dir(fuzz_dir).join(with_extension);
    if candidate.exists() {
        return Ok(candidate);
    }

    bail!(
        "dictionary `{}` does not exist; tried the path and `{}`",
        reference.display(),
        dictionary_dir(fuzz_dir).display()
    )
}

fn import_directory(directory: &Path, format: DictionaryFormat) -> Result<Vec<DictionaryEntry>> {
    let mut paths = Vec::new();
    for entry in fs::read_dir(directory).with_context(|| {
        format!(
            "failed to read dictionary directory {}",
            directory.display()
        )
    })? {
        let entry = entry?;
        let path = entry.path();
        if path.is_file()
            && matches!(
                path.extension().and_then(OsStr::to_str),
                Some("dict" | "txt" | "words")
            )
        {
            paths.push(path);
        }
    }
    paths.sort();

    let mut entries = Vec::new();
    for path in paths {
        entries.extend(parse_source(&path, format)?);
    }
    Ok(deduplicate(entries))
}

fn parse_quoted_value(raw: &str) -> Result<Vec<u8>> {
    let mut chars = raw.chars();
    if chars.next() != Some('"') {
        bail!("quoted dictionary value must start with `\"`");
    }

    let mut value = Vec::new();
    while let Some(ch) = chars.next() {
        match ch {
            '"' => {
                if chars.next().is_some() {
                    bail!("unexpected characters after closing quote");
                }
                return Ok(value);
            }
            '\\' => match chars.next() {
                Some('\\') => value.push(b'\\'),
                Some('"') => value.push(b'"'),
                Some('n') => value.push(b'\n'),
                Some('r') => value.push(b'\r'),
                Some('t') => value.push(b'\t'),
                Some('x') => {
                    let high = chars.next().context("incomplete \\x escape")?;
                    let low = chars.next().context("incomplete \\x escape")?;
                    let hex: String = [high, low].into_iter().collect();
                    let byte = u8::from_str_radix(&hex, 16)
                        .with_context(|| format!("invalid hex escape \\x{hex}"))?;
                    value.push(byte);
                }
                Some(other) => {
                    let mut buffer = [0; 4];
                    value.extend_from_slice(other.encode_utf8(&mut buffer).as_bytes());
                }
                None => bail!("unterminated escape sequence"),
            },
            _ => {
                let mut buffer = [0; 4];
                value.extend_from_slice(ch.encode_utf8(&mut buffer).as_bytes());
            }
        }
    }

    bail!("unterminated quoted dictionary value")
}

fn escape_value(value: &[u8]) -> String {
    let mut result = String::with_capacity(value.len());
    for &byte in value {
        match byte {
            b'\\' => result.push_str("\\\\"),
            b'"' => result.push_str("\\\""),
            b'\n' => result.push_str("\\n"),
            b'\r' => result.push_str("\\r"),
            b'\t' => result.push_str("\\t"),
            0x20..=0x7e => result.push(byte as char),
            _ => result.push_str(&format!("\\x{byte:02x}")),
        }
    }
    result
}

fn is_valid_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    match chars.next() {
        Some(ch) if ch.is_ascii_alphabetic() || ch == '_' => {}
        _ => return false,
    }
    chars.all(|ch| ch.is_ascii_alphanumeric() || ch == '_')
}

fn deduplicate(entries: Vec<DictionaryEntry>) -> Vec<DictionaryEntry> {
    let mut seen = std::collections::HashSet::new();
    entries
        .into_iter()
        .filter(|entry| seen.insert(entry.value.clone()))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_named_escaped_and_hex_entries() {
        let dict = r#"
# comment
kw1="blah"
kw2="\"ac\\dc\""
magic="\xF7\xF8"
bare-token
"#;
        let entries = parse_dictionary(dict).unwrap();
        assert_eq!(entries.len(), 4);
        assert_eq!(entries[0].name.as_deref(), Some("kw1"));
        assert_eq!(entries[0].value, b"blah");
        assert_eq!(entries[1].value, b"\"ac\\dc\"");
        assert_eq!(entries[2].value, vec![0xf7, 0xf8]);
        assert_eq!(entries[3].value, b"bare-token");
    }

    #[test]
    fn round_trips_binary_values() {
        let entries = vec![
            DictionaryEntry {
                name: Some("binary".into()),
                value: vec![0, 1, b'A', b'"', b'\\', 0xff, b'\n'],
            },
            DictionaryEntry {
                name: None,
                value: b"token".to_vec(),
            },
        ];
        let serialized = serialize_dictionary(&entries);
        let parsed = parse_dictionary(&serialized).unwrap();
        assert_eq!(parsed[0], entries[0]);
        assert_eq!(parsed[1].name.as_deref(), Some("token_0002"));
        assert_eq!(parsed[1].value, b"token");
    }

    #[test]
    fn imports_word_lists_and_deduplicates() {
        let words = parse_word_list("alpha\nalpha\n# beta\nbeta\n");
        assert_eq!(words.len(), 2);
        assert_eq!(words[0].value, b"alpha");
        assert_eq!(words[1].value, b"beta");

        let merged = merge_entries(
            vec![DictionaryEntry {
                name: None,
                value: b"alpha".into(),
            }],
            vec![
                DictionaryEntry {
                    name: None,
                    value: b"alpha".into(),
                },
                DictionaryEntry {
                    name: None,
                    value: b"beta".into(),
                },
            ],
        );
        assert_eq!(merged.len(), 2);
    }

    #[test]
    fn parses_unnamed_value_containing_equals() {
        let entries = parse_dictionary("\"a=b=c\"\n").unwrap();
        assert_eq!(entries.len(), 1);
        assert_eq!(entries[0].value, b"a=b=c");
        assert_eq!(entries[0].name, None);
    }
}
